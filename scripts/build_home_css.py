"""Bundle homepage styles without changing cascade order or relative asset URLs."""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CSS = ROOT / "assets" / "css"
OUTPUT = CSS / "home.css"


def build():
    tokens = (CSS / "tokens.css").read_text()
    main = (CSS / "main.css").read_text()
    enterprise = (CSS / "enterprise.css").read_text()
    imported_tokens = '@import "./tokens.css";'
    if main.count(imported_tokens) != 1:
        raise ValueError("Expected one tokens import; review stylesheet bundling.")
    main = main.replace(imported_tokens, "", 1).lstrip()
    bundled = "\n".join(
        [
            "/* Generated by scripts/build_home_css.py. Edit source styles, not this file. */",
            tokens.rstrip(),
            main.rstrip(),
            enterprise.rstrip(),
            "",
        ]
    )
    if "@import" in bundled:
        raise ValueError("Unresolved CSS import in homepage bundle.")
    return bundled


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    bundled = build()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != bundled:
            raise SystemExit("Homepage CSS is stale. Run python3 scripts/build_home_css.py")
        print("Homepage CSS bundle is current.")
    else:
        OUTPUT.write_text(bundled)
        print(f"Built {OUTPUT.relative_to(ROOT)} ({len(bundled.encode())} bytes).")


if __name__ == "__main__":
    main()
